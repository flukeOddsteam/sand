CASUAL_TAIL = ["", "", "", "", "อะ", " 555", "นะ", "อ่ะ"]


def _pick(r, text):
    return r.choice(text) if isinstance(text, list) else text


def walk(r, user_nodes, slots, out):
    """เดินหนึ่งเส้นทางในต้นไม้บทสนทนา"""
    utext, replies = r.choice(user_nodes)
    u = _pick(r, utext).format(**slots)
    if not out and r.random() < 0.3 and not u.endswith(("!", "5")):
        u += r.choice(CASUAL_TAIL)                       # คนพิมพ์แชทชอบต่อท้ายแบบนี้
    out.append(("u", u))
    stext, nxt = r.choice(replies)
    out.append(("s", _pick(r, stext).format(**slots)))
    if nxt and r.random() < 0.88:                        # บางครั้งคุยสั้นๆ แล้วจบเลย
        walk(r, nxt, slots, out)
    return out


def dialogue(r):
    slots = {k: r.choice(v) for k, v in SLOTS.items()}
    slots["food2"] = r.choice([f for f in SLOTS["food"] if f != slots["food"]])
    slots["news"] = r.choice(NEWS)
    turns = walk(r, r.choice(SCENES), slots, [])
    return "".join((U if who == "u" else S) + text.strip() + "\n" for who, text in turns)


def build(n=900, seed=11):
    """บทสนทนาต่อเนื่อง n เรื่อง (ไม่ซ้ำกัน) — ตอนรวมเป็นบทเรียนให้คั่นด้วยบรรทัดว่าง = จบเรื่อง เริ่มเรื่องใหม่"""
    r = random.Random(seed)
    seen, out = set(), []
    for _ in range(n * 30):
        if len(out) >= n:
            break
        d = dialogue(r)
        if d not in seen:
            seen.add(d)
            out.append(d)
    return out


