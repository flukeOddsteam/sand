def pair(q, a):
    return f"{U}{q}\n{S}{a}\n"


def build(seed=7):
    rnd = random.Random(seed)
    out = []
    for q, a in DIALOGUES:
        out += [pair(q, a)] * 3
    for _ in range(500):
        a, b = rnd.randint(0, 20), rnd.randint(0, 20)
        if rnd.random() < 0.6:
            q = rnd.choice([f"{a} + {b} เท่ากับเท่าไร", f"{a} + {b} = ?", f"{a} บวก {b}"])
            out.append(pair(q, f"{a} + {b} = {a + b}"))
        else:
            a, b = max(a, b), min(a, b)
            q = rnd.choice([f"{a} - {b} เท่ากับเท่าไร", f"{a} - {b} = ?", f"{a} ลบ {b}"])
            out.append(pair(q, f"{a} - {b} = {a - b}"))
    for _ in range(80):
        a = rnd.randint(1, 15)
        b = a + rnd.randint(2, 6)
        out.append(pair(f"นับ {a} ถึง {b}", " ".join(str(i) for i in range(a, b + 1))))
    for i, w in enumerate(NUM_TH):
        out += [pair(f"เลข {i} อ่านว่า", w), pair(f"{w} คือเลขอะไร", str(i))]
    for i, d in enumerate(DAYS):
        out += [pair(f"วันต่อจาก{d}คือวันอะไร", DAYS[(i + 1) % 7]),
                pair(f"วันก่อน{d}คือวันอะไร", DAYS[(i - 1) % 7])] * 2
    for a, b in OPPOSITES:
        out += [pair(f"คำตรงข้ามของ {a}", b), pair(f"คำตรงข้ามของ {b}", a)] * 2
    for en, th in WORDS:
        out += [pair(f"{en} แปลว่าอะไร", th), pair(f"{th} ภาษาอังกฤษคือ", en)] * 2
    rnd.shuffle(out)
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
